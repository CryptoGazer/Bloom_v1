/* Local backend + Playwright/Chrome. Real routing and MP3 decoding, stubbed provider responses (no credits).
   VOICE_TEST_EN/RO can point at MP3s generated by ElevenLabs. Otherwise a short WAV is used for playback tests.
   NODE_PATH=/tmp/bezna-voice-tools/node_modules node scripts/testing/check_voice_ui.cjs */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');
const base = process.env.GEMINI_TEST_URL || 'http://127.0.0.1:8019';
const origin = new URL(base).origin;
function fixture(lang) {
  const path = process.env['VOICE_TEST_' + lang.toUpperCase()];
  if (path) return { body: fs.readFileSync(path), contentType: 'audio/mpeg' };
  const b = Buffer.alloc(44 + 16000);
  b.write('RIFF'); b.writeUInt32LE(b.length - 8, 4); b.write('WAVEfmt ', 8);
  b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22);
  b.writeUInt32LE(8000, 24); b.writeUInt32LE(16000, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34);
  b.write('data', 36); b.writeUInt32LE(16000, 40);
  return { body: b, contentType: 'audio/wav' };
}
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    for (const view of ['desktop', 'mobile', 'android-bridge']) for (const lang of ['en', 'ro']) {
      const mobile = view !== 'desktop', native = view === 'android-bridge';
      const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 },
        permissions: ['geolocation'], geolocation: { latitude: 45.749852, longitude: 21.240281 } });
      await context.addInitScript(isNative => {
        localStorage.setItem('lightmap.lang', 'ru'); // old installations must still load
        window.voiceTest = { system: [], played: [] };
        speechSynthesis.speak = u => voiceTest.system.push({ text: u.text, lang: u.lang });
        speechSynthesis.cancel = () => {};
        if (isNative) window.BeznaNative = {
          speak: (text, lang) => voiceTest.system.push({ text, lang }), stopSpeaking() {}, nav() {},
        };
        const play = HTMLMediaElement.prototype.play;
        HTMLMediaElement.prototype.play = function () {
          return play.call(this).then(() => { if (this.src.startsWith('blob:')) voiceTest.played.push(this.src); });
        };
      }, native);
      const page = await context.newPage(), errors = [], requests = [];
      page.on('pageerror', e => errors.push(e.message));
      let response = 'ok';
      await page.route('**/*', async route => {
        const url = new URL(route.request().url());
        if (url.origin !== origin) return route.abort();
        if (url.pathname === '/api/health') return route.fulfill({ json: { ok: true, ask: true, speak: ['en', 'ro'] } });
        if (url.pathname === '/api/speak') {
          requests.push({ lang: url.searchParams.get('lang'), text: url.searchParams.get('text') });
          if (response === 'error') return route.fulfill({ status: 503, json: { detail: { code: 'voice_busy' } } });
          if (response === 'slow') await new Promise(r => setTimeout(r, 3000));
          return route.fulfill(response === 'invalid' ? { contentType: 'audio/mpeg', body: Buffer.alloc(500) } : fixture(lang));
        }
        return route.continue();
      });
      const path = mobile ? '/m/' : '/';
      await page.goto(base + path + '?lang=' + lang);
      await page.waitForFunction(() => typeof summary !== 'undefined' && summary && typeof voice !== 'undefined');
      assert.equal(await page.evaluate(() => LANG), lang);
      assert.deepEqual(await page.evaluate(() => LANGS), ['ro', 'en']);
      if (mobile) await page.locator('[data-act="lang"]').click();
      assert.equal(await page.locator('[data-lang="ru"]').count(), 0);
      if (mobile) await page.locator('[data-act="lang"]').click();
      await page.evaluate(() => {
        setPoint('A', [45.749852, 21.240281], 'Căminul C12');
        setPoint('B', [45.753113, 21.2257], 'Piața Victoriei');
        compute();
      });
      await page.waitForFunction(() => plan && plan.routes.better_lit.length_m > 0);
      await page.locator(mobile ? '[data-act="voice"]' : '#voice-toggle').first().click();
      await page.waitForFunction(() => voiceTest.played.length > 0);
      assert.equal((await page.evaluate(() => voiceTest.system)).length, 0, 'Cloud must precede the system voice');
      if (mobile) {
        const before = requests.length;
        await page.locator('[data-act="start"]').click();
        await page.waitForFunction(() => nav && screen === 'nav');
        await page.waitForFunction(n => voiceTest.played.length > n, 1);
        assert.ok(requests.length > before, 'Navigator must request a direction');
        await page.locator('[data-act="navStop"]').click();
      } else assert.ok(requests[0].text.includes(lang === 'en' ? 'Confirmed lighting' : 'Iluminat confirmat'));

      // Provider failure and an MP3 decode failure each speak once, in the selected language.
      for (const failure of ['error', 'invalid', 'slow']) {
        response = failure;
        const before = await page.evaluate(() => voiceTest.system.length);
        await page.evaluate(text => voice.speak(text), `${failure} ${lang}`);
        await page.waitForFunction(n => voiceTest.system.length === n + 1, before);
        assert.equal((await page.evaluate(() => voiceTest.system.at(-1))).lang, lang === 'en' ? 'en-GB' : 'ro-RO');
        if (failure === 'slow') {
          const played = await page.evaluate(() => voiceTest.played.length);
          await page.waitForTimeout(700);
          assert.equal(await page.evaluate(() => voiceTest.played.length), played, 'Late audio must not repeat a direction');
        }
      }
      // Muting discards audio still being fetched and the pending fallback timer.
      const before = await page.evaluate(() => ({ played: voiceTest.played.length, system: voiceTest.system.length }));
      await page.evaluate(() => { voice.speak('cancelled phrase'); voice.hush(); });
      await page.waitForTimeout(3100);
      assert.deepEqual(await page.evaluate(() => ({ played: voiceTest.played.length, system: voiceTest.system.length })), before);
      assert.ok(requests.every(r => r.lang === lang));
      assert.deepEqual(errors, []);
      await page.goto(base + path + '?lang=ru');
      assert.equal(await page.evaluate(() => LANG), 'ro');
      assert.equal(await page.locator('[data-lang="ru"]').count(), 0);
      console.log(JSON.stringify({ view, lang, status: 'PASS', checks: 'route, audio playback, provider/decode/timeout fallback, cancellation, EN/RO only' }));
      await context.close();
    }
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
